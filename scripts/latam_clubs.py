def build_map(table, recent=False):
    """grafia normalizada -> [(de, até, clube)]"""
    out = {}
    for club, names in table.items():
        if club.startswith("_"):
            continue
        for n in names:
            a, b = 0, 9999
            if isinstance(n, tuple):
                n, a, b = n
            out.setdefault(key(n), []).append((a, b, club))
    return out


def resolve(m, raw, year):
    for a, b, club in m.get(key(raw), ()):
        if a <= year <= b:
            return club
    return None
