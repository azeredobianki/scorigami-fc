"""Clubes da Argentina e do México: grafias das fontes -> nome do clube.

As chaves são comparadas sem acento, sem diferença de maiúsculas e com os
espaços normalizados (ver `key`). Um nome pode valer para um clube só em
alguns anos: (grafia, primeiro ano, último ano).
"""

import re
import unicodedata


def key(s):
    s = unicodedata.normalize("NFKD", s.replace("´", "'").replace("`", "'")).encode("ascii", "ignore").decode()
    s = re.sub(r"\s*\(\s*", " (", s.lower())
    s = re.sub(r"\s*\)", ")", s)
    s = re.sub(r"\s+", " ", s).strip(" .,;:")
    return s


